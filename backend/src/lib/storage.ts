import { createHash, createHmac, timingSafeEqual } from "node:crypto";
import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";
import { env } from "../config/env";
import { AppError, badRequest } from "./errors";

/** The object does not exist (deleted, or lost when an ephemeral disk was reset). */
export class StorageNotFoundError extends Error {
  constructor() {
    super("Stored file not found");
    this.name = "StorageNotFoundError";
  }
}

/**
 * Storage could not be reached or refused the request (network, credentials,
 * permissions, quota). Surfaces as HTTP 503 so it is never mistaken for a missing file.
 */
export class StorageUnavailableError extends AppError {
  constructor(operation: "upload" | "download" | "delete" | "sign", cause?: unknown) {
    super(
      503,
      operation === "upload"
        ? "Document storage is unavailable, so nothing was saved. Please try again in a moment."
        : "Document storage is unavailable right now. Please try again in a moment.",
      "STORAGE_UNAVAILABLE",
    );
    this.name = "StorageUnavailableError";
    // Keep the provider's error for server logs only (never sent to clients).
    (this as { cause?: unknown }).cause = cause;
  }
}

const isNotFound = (e: unknown) => {
  const x = e as { name?: string; Code?: string; code?: string; $metadata?: { httpStatusCode?: number } };
  return x?.code === "ENOENT" || x?.name === "NoSuchKey" || x?.name === "NotFound" || x?.Code === "NoSuchKey" || x?.$metadata?.httpStatusCode === 404;
};

/**
 * Private document storage.
 *
 * - Every object lives under `company-<id>/<random 128-bit hex key>`: the key is
 *   generated by the server, never derived from user input, so path traversal is
 *   impossible and one tenant cannot address another tenant's objects.
 * - Nothing is ever public. Downloads go through an authenticated, tenant-checked
 *   API call that either streams the file or issues a short-lived signed link.
 * - "local" writes to UPLOAD_DIR. On hosts with an ephemeral disk (Render free
 *   plan) those files disappear on every deploy/restart: use "s3" in production.
 */

// ───────────────────────── Upload validation ─────────────────────────

/** Allowed upload types, verified by declared MIME type, file extension AND file signature. */
const TYPES: Record<string, { ext: string[]; sig: (b: Buffer) => boolean }> = {
  "application/pdf": { ext: [".pdf"], sig: (b) => b.subarray(0, 5).toString("latin1") === "%PDF-" },
  "image/png": { ext: [".png"], sig: (b) => b.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) },
  "image/jpeg": { ext: [".jpg", ".jpeg"], sig: (b) => b.length > 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff },
  "image/webp": {
    ext: [".webp"],
    sig: (b) => b.subarray(0, 4).toString("latin1") === "RIFF" && b.subarray(8, 12).toString("latin1") === "WEBP",
  },
};

export const ALLOWED_MIME_TYPES = Object.keys(TYPES);
export const IMAGE_MIME_TYPES = ALLOWED_MIME_TYPES.filter((m) => m.startsWith("image/"));

/** Rejects disallowed types and files whose bytes do not match their declared type. */
export function assertAllowedFile(mimeType: string, buffer: Buffer, fileName?: string, allowed: readonly string[] = ALLOWED_MIME_TYPES) {
  const t = TYPES[mimeType];
  if (!t || !allowed.includes(mimeType)) {
    const names = allowed.map((m) => m.split("/")[1].toUpperCase()).join(", ");
    throw badRequest(`File type ${mimeType || "unknown"} is not allowed. Use ${names}.`);
  }
  if (buffer.length === 0) throw badRequest("The file is empty");
  if (!t.sig(buffer)) throw badRequest("File content does not match its declared type");
  if (fileName) {
    const ext = path.extname(fileName).toLowerCase();
    // Camera captures and canvas exports may arrive without an extension ("blob"); that is fine.
    if (ext && !t.ext.includes(ext)) throw badRequest(`File extension ${ext} does not match its type (${mimeType})`);
  }
}

/** A display-only file name: no directories, control characters or quotes; bounded length. */
export function safeFileName(name: string | undefined, fallback = "document"): string {
  const base = path.basename(String(name ?? "").replace(/\\/g, "/"));
  // eslint-disable-next-line no-control-regex
  const cleaned = base.replace(/[\u0000-\u001f\u007f"<>:|?*/\\]/g, "_").replace(/^\.+/, "").trim();
  return (cleaned || fallback).slice(0, 150);
}

export function sha256(data: Buffer): string {
  return createHash("sha256").update(data).digest("hex");
}

// ───────────────────────── Drivers ─────────────────────────

export interface StorageDriver {
  readonly name: "local" | "s3";
  /** False when files can vanish on restart/redeploy (local disk on an ephemeral host). */
  readonly persistent: boolean;
  put(companyId: number, key: string, data: Buffer, mimeType: string): Promise<void>;
  get(companyId: number, key: string): Promise<Buffer>;
  delete(companyId: number, key: string): Promise<void>;
  /** A direct, time-limited download link, when the backend can mint one; otherwise null. */
  presignedGetUrl(companyId: number, key: string, fileName: string, mimeType: string, ttlSeconds: number): Promise<string | null>;
}

/** Reserved id for the operator self-test (tenant ids start at 1), kept apart from all company data. */
export const HEALTHCHECK_COMPANY_ID = 0;

function objectKey(companyId: number, key: string) {
  if (!Number.isInteger(companyId) || companyId < 0) throw badRequest("Invalid company");
  if (!/^[a-f0-9]{32}$/.test(key)) throw badRequest("Invalid storage key");
  return companyId === HEALTHCHECK_COMPANY_ID ? `system-healthcheck/${key}` : `company-${companyId}/${key}`;
}

export class LocalStorage implements StorageDriver {
  readonly name = "local" as const;
  constructor(
    private readonly rootDir: string,
    readonly persistent: boolean,
  ) {}

  private file(companyId: number, key: string) {
    // Legacy layout (<root>/<companyId>/<key>) is kept so files uploaded before this module still resolve.
    objectKey(companyId, key);
    return path.join(path.resolve(this.rootDir), String(companyId), key);
  }

  // The MIME type is recorded on the Attachment row; the file itself is stored as raw bytes.
  async put(companyId: number, key: string, data: Buffer, _mimeType?: string) {
    const p = this.file(companyId, key);
    try {
      await mkdir(path.dirname(p), { recursive: true });
      await writeFile(p, data, { flag: "wx" });
    } catch (e) {
      throw new StorageUnavailableError("upload", e);
    }
  }

  async get(companyId: number, key: string) {
    try {
      return await readFile(this.file(companyId, key));
    } catch (e) {
      if (isNotFound(e)) throw new StorageNotFoundError();
      throw new StorageUnavailableError("download", e);
    }
  }

  async delete(companyId: number, key: string) {
    await unlink(this.file(companyId, key)).catch(() => undefined);
  }

  async presignedGetUrl() {
    return null;
  }
}

export class S3Storage implements StorageDriver {
  readonly name = "s3" as const;
  readonly persistent = true;
  private readonly client: S3Client;

  constructor(
    private readonly bucket: string,
    opts: { region: string; endpoint?: string; accessKeyId: string; secretAccessKey: string; forcePathStyle: boolean },
  ) {
    this.client = new S3Client({
      region: opts.region,
      endpoint: opts.endpoint,
      forcePathStyle: opts.forcePathStyle,
      credentials: { accessKeyId: opts.accessKeyId, secretAccessKey: opts.secretAccessKey },
      // Newer SDKs add CRC checksums (and aws-chunked trailers) to every upload by default;
      // several S3-compatible providers reject those. Only send them when an API requires it.
      requestChecksumCalculation: "WHEN_REQUIRED",
      responseChecksumValidation: "WHEN_REQUIRED",
      maxAttempts: 3,
    });
  }

  async put(companyId: number, key: string, data: Buffer, mimeType: string) {
    const Key = objectKey(companyId, key);
    try {
      await this.client.send(new PutObjectCommand({ Bucket: this.bucket, Key, Body: data, ContentType: mimeType, ContentLength: data.length }));
    } catch (e) {
      throw new StorageUnavailableError("upload", e);
    }
  }

  async get(companyId: number, key: string) {
    const Key = objectKey(companyId, key);
    try {
      const r = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key }));
      if (!r.Body) throw new StorageNotFoundError();
      return Buffer.from(await r.Body.transformToByteArray());
    } catch (e) {
      if (e instanceof StorageNotFoundError || isNotFound(e)) throw new StorageNotFoundError();
      throw new StorageUnavailableError("download", e);
    }
  }

  async delete(companyId: number, key: string) {
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: objectKey(companyId, key) })).catch(() => undefined);
  }

  async presignedGetUrl(companyId: number, key: string, fileName: string, mimeType: string, ttlSeconds: number) {
    // Signing is local (no network call), but a malformed configuration still fails here.
    return getSignedUrl(
      this.client,
      new GetObjectCommand({
        Bucket: this.bucket,
        Key: objectKey(companyId, key),
        ResponseContentType: mimeType,
        ResponseContentDisposition: contentDisposition(fileName),
      }),
      { expiresIn: ttlSeconds },
    );
  }
}

function createStorage(): StorageDriver {
  if (env.STORAGE_DRIVER === "s3") {
    return new S3Storage(env.S3_BUCKET!, {
      region: env.S3_REGION,
      endpoint: env.S3_ENDPOINT,
      accessKeyId: env.S3_ACCESS_KEY_ID!,
      secretAccessKey: env.S3_SECRET_ACCESS_KEY!,
      forcePathStyle: env.S3_FORCE_PATH_STYLE,
    });
  }
  // Local disk is only treated as persistent outside production; production deployments
  // (Render free plan in particular) wipe the disk on every deploy/restart.
  return new LocalStorage(env.UPLOAD_DIR, env.NODE_ENV !== "production");
}

export const storage: StorageDriver = createStorage();

/**
 * Read a stored object, returning null ONLY when it does not exist. Storage
 * outages propagate as StorageUnavailableError (HTTP 503) instead of looking
 * like a missing file.
 */
export async function readIfExists(companyId: number, key: string, driver: StorageDriver = storage): Promise<Buffer | null> {
  try {
    return await driver.get(companyId, key);
  } catch (e) {
    if (e instanceof StorageNotFoundError) return null;
    throw e;
  }
}

export function storageStatus(driver: StorageDriver = storage) {
  return {
    driver: driver.name,
    persistent: driver.persistent,
    warning: driver.persistent
      ? null
      : "Uploaded documents are stored on the server's local disk, which is wiped on redeploy/restart. Configure STORAGE_DRIVER=s3 before relying on uploads in production.",
  };
}

// ───────────────────────── Signed links (local driver) ─────────────────────────

export function contentDisposition(fileName: string) {
  const ascii = safeFileName(fileName).replace(/[^\x20-\x7e]/g, "_");
  return `attachment; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(safeFileName(fileName))}`;
}

interface FileTokenPayload {
  c: number; // company
  k: string; // storage key
  n: string; // download file name
  m: string; // mime type
  e: number; // expiry (unix seconds)
}

// Domain-separated from the JWT signing key so a file token can never be used as a session token.
const fileKey = () => createHmac("sha256", env.JWT_SECRET).update("raahsetu:file-download:v1").digest();

export function signFileToken(p: Omit<FileTokenPayload, "e">, ttlSeconds: number, now = Date.now()): string {
  const body = Buffer.from(JSON.stringify({ ...p, e: Math.floor(now / 1000) + ttlSeconds })).toString("base64url");
  const sig = createHmac("sha256", fileKey()).update(body).digest("base64url");
  return `${body}.${sig}`;
}

export function verifyFileToken(token: string, now = Date.now()): FileTokenPayload | null {
  const [body, sig] = token.split(".");
  if (!body || !sig || token.length > 2000) return null;
  const expected = createHmac("sha256", fileKey()).update(body).digest();
  const given = Buffer.from(sig, "base64url");
  if (given.length !== expected.length || !timingSafeEqual(given, expected)) return null;
  try {
    const p = JSON.parse(Buffer.from(body, "base64url").toString("utf8")) as FileTokenPayload;
    if (typeof p.e !== "number" || p.e * 1000 < now) return null;
    if (!Number.isInteger(p.c) || p.c < 1) return null; // never the self-test prefix
    objectKey(p.c, p.k);
    return p;
  } catch {
    return null;
  }
}

/**
 * Time-limited download link for a stored file. The caller MUST have checked the
 * user's permission and tenant before calling this.
 */
export async function signedDownloadUrl(companyId: number, key: string, fileName: string, mimeType: string) {
  const ttl = env.SIGNED_URL_TTL_SECONDS;
  const direct = await storage.presignedGetUrl(companyId, key, fileName, mimeType, ttl);
  const url = direct ?? `/api/files/${signFileToken({ c: companyId, k: key, n: safeFileName(fileName), m: mimeType }, ttl)}`;
  return { url, expiresAt: new Date(Date.now() + ttl * 1000).toISOString() };
}
